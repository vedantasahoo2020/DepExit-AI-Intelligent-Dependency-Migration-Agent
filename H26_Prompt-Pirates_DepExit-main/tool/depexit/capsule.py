"""Write Dependency Exit Capsules (JSON for machines, Markdown for humans).

Every section is tagged:  OBSERVED = measured by DepExit,  AI = generated by Gemma 4.
"""
import json
from pathlib import Path

from . import CAPSULE_SCHEMA
from .env import normalise_path_text as env_text

ICON = {
    "verified_improvement": "✅", "verified_no_regression": "✅", "regression": "❌",
    "install_failed": "❌", "not_applied": "⚠️", "incomplete": "⚠️", "kept": "➖",
    "ai_failed": "⚠️", "not_attempted": "➖", None: "➖",
}
MEANING = {
    "verified_improvement": "migration applied, previously failing checks now pass, no regressions",
    "verified_no_regression": "migration applied, every check that passed before still passes",
    "regression": "migration applied but some previously passing tests now fail",
    "install_failed": "the migrated dependency set could not be installed",
    "not_applied": "the AI's code changes could not be applied to the repository",
    "incomplete": "old dependency is still referenced after the migration",
    "kept": "AI recommended keeping the dependency",
    "ai_failed": "the AI call failed, only observed evidence is available",
    "not_attempted": "AI disabled, only observed evidence is available",
}
LIMITATIONS = [
    "Verification is only as strong as the repository's own test suite; untested code paths are not proven.",
    "Static analysis cannot see dynamic imports (importlib, __import__, plugins loaded by name).",
    "Each install route (requirements files / pyproject) is verified separately; other environments "
    "(other OSes, other Python versions) were not tested.",
    "Network-dependent behaviour is only exercised where the tests do so.",
    "Security vulnerabilities are out of scope for this run.",
]


def write_all(out_dir, run_info, baseline, deps, selected, combined, ai_calls, organized=None, forecast=None):
    out_dir = Path(out_dir)
    (out_dir / "dependencies").mkdir(parents=True, exist_ok=True)
    selected_names = {d["name"] for d in selected}
    capsules = []
    for dep in deps:
        if dep["name"] not in selected_names:
            continue
        cap = build(dep, run_info, baseline)
        capsules.append(cap)
        base = out_dir / "dependencies" / dep["name"]
        base.with_suffix(".json").write_text(json.dumps(cap, indent=2, default=str), encoding="utf-8", newline="\n")
        base.with_suffix(".md").write_text(to_markdown(cap), encoding="utf-8", newline="\n")
        last = (dep.get("attempts") or [{}])[-1]
        if last.get("diff"):
            base.with_suffix(".patch").write_text(last["diff"], encoding="utf-8", newline="\n")
    if combined and combined.get("diff"):
        (out_dir / "combined-migration.patch").write_text(combined["diff"], encoding="utf-8", newline="\n")
    elif len([d for d in selected if d.get("verdict") in ("verified_improvement", "verified_no_regression")]) == 1:
        only = next(d for d in selected if d.get("verdict") in ("verified_improvement", "verified_no_regression"))
        (out_dir / "combined-migration.patch").write_text(only["attempts"][-1]["diff"], encoding="utf-8", newline="\n")
    if organized and organized.get("diff"):
        (out_dir / "organizer.patch").write_text(organized["diff"], encoding="utf-8", newline="\n")
    summary = {
        "schema": CAPSULE_SCHEMA + "/index",
        "run": run_info,
        "baseline": {r: _route_summary(b) for r, b in baseline.items()},
        "all_dependencies": [{"name": d["name"], "level": d["level"], "score": d["score"],
                              "indicators": sorted({i["id"] for i in d["indicators"]}),
                              "selected": d["name"] in selected_names, "verdict": d.get("verdict")} for d in deps],
        "combined_migration": _combined_summary(combined),
        "organizer": None if not organized else {k: organized[k] for k in
                                                  ("actions", "log", "ai_annotations", "ai_error", "comparison", "verdict", "applies_on_top_of")}
        | {"patch": "organizer.patch", "diff": organized.get("diff")},
        "forecast": forecast,
        "capsules": ["dependencies/%s.json" % c["dependency"]["name"] for c in capsules],
    }
    (out_dir / "capsule.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8", newline="\n")
    (out_dir / "ai_calls.json").write_text(json.dumps(ai_calls, indent=2), encoding="utf-8", newline="\n")
    (out_dir / "README.md").write_text(index_markdown(summary, capsules, combined), encoding="utf-8", newline="\n")
    if (out_dir / "combined-migration.patch").exists():
        summary["combined_patch"] = "combined-migration.patch"
        (out_dir / "capsule.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8", newline="\n")
    return {"index": out_dir / "README.md", "json": out_dir / "capsule.json"}


def _route_summary(b):
    return {"install_ok": b.get("install", {}).get("ok"),
            "tests": (b.get("tests") or {}).get("counts"),
            "failing": sorted(t for t, v in ((b.get("tests") or {}).get("tests") or {}).items()
                              if v["outcome"] in ("failed", "error")),
            "warnings": (b.get("tests") or {}).get("warnings", [])}


def _combined_summary(c):
    if not c:
        return None
    return {"dependencies": c["dependencies"], "verdict": c["verdict"], "comparison": c["comparison"],
            "apply": c["apply"], "patch": "combined-migration.patch"}


def build(dep, run_info, baseline):
    attempts = dep.get("attempts") or []
    last = attempts[-1] if attempts else {}
    proposal = last.get("proposal") or {}
    review = (dep.get("ai") or {}).get("review") or {}
    comp = last.get("comparison") or {}

    observed_gaps, observed_concerns = [], []
    for route, r in (comp.get("routes") or {}).items():
        for t in r["regressed"]:
            observed_gaps.append("[%s] regression: %s - %s" % (route, t, r["regression_details"].get(t, "")[:200]))
        for t in r["still_failing"]:
            observed_concerns.append("[%s] still failing after migration: %s" % (route, t))
        for w in r["warnings_added"]:
            observed_gaps.append("[%s] new warning: %s" % (route, w))
        if r["install_ok_after"] is False:
            observed_gaps.append("[%s] install failed after migration" % route)
    for ref in comp.get("residual_references") or []:
        observed_gaps.append("old dependency still referenced: %s" % ref)
    for e in (last.get("apply") or {}).get("errors", []):
        observed_gaps.append("change not applied: %s" % e)
    for mod, by_route in (last.get("replacement_imports") or {}).items():
        for route, res in by_route.items():
            if not res["ok"]:
                observed_gaps.append("[%s] replacement module `%s` fails to import: %s" % (route, mod, res["error"]))
    tests_cover = any(u["file"].startswith(("tests/", "test")) for u in dep["usage"]["usages"])

    return {
        "schema": CAPSULE_SCHEMA,
        "generated_by": run_info["tool"],
        "target": {"repository": run_info["target"], "commit": run_info["commit"], "python": run_info["python"]},
        "dependency": {
            "name": dep["name"], "modules": dep["modules"], "installed_version": dep.get("installed_version"),
            "latest_version": dep["pypi"].get("latest_version"), "console_scripts": dep.get("console_scripts", []),
        },
        "verdict": {"value": dep.get("verdict"), "meaning": MEANING.get(dep.get("verdict"), ""),
                    "attempts": len(attempts), "source": "observed"},
        "observed": {
            "declarations": dep["declarations"],
            "pypi": dep["pypi"],
            "risk": {"level": dep["level"], "score": dep["score"], "indicators": dep["indicators"]},
            "usage": {"imports": dep["usage"]["imports"], "usages": dep["usage"]["usages"],
                      "non_python_references": dep["text_references"]},
            "baseline": {r: _route_summary(b) for r, b in baseline.items()},
            "attempts": [_attempt_obs(a) for a in attempts],
            "compatibility_gaps": observed_gaps,
            "open_concerns": observed_concerns,
        },
        "ai_generated": {
            "model": run_info.get("ai_model"),
            "enabled": (dep.get("ai") or {}).get("enabled", False),
            "error": (dep.get("ai") or {}).get("error"),
            "assessment": proposal.get("assessment"),
            "action": proposal.get("action"),
            "proposed_replacement": proposal.get("replacement"),
            "manifest_changes": {"remove": proposal.get("remove_requirements"), "add": proposal.get("add_requirements")},
            "code_changes": proposal.get("code_changes"),
            "migration_steps": proposal.get("migration_steps"),
            "suggested_tests": proposal.get("suggested_tests"),
            "risks": proposal.get("risks"),
            "proposal_history": [a.get("proposal", {}).get("action") for a in attempts],
            "validation_problems_repaired": (dep.get("ai") or {}).get("validation_problems"),
            "review": review,
            "note": "AI-generated content. Only the 'observed' section is verified by execution.",
        },
        "limitations": LIMITATIONS + ([] if tests_cover else
                                      ["No test file exercises this dependency directly; behaviour equivalence relies on indirect coverage."]),
    }


def _attempt_obs(a):
    out = {"attempt": a["n"], "verdict": a.get("verdict"), "skipped": a.get("skipped")}
    if "apply" in a:
        out["apply"] = a["apply"]
        out["comparison"] = a["comparison"]
        out["replacement_imports"] = a["replacement_imports"]
        out["installs"] = {r: v["install"] for r, v in a["verification"].items()}
        out["test_runs"] = {r: {k: v.get("tests", {}).get(k) for k in ("command", "counts", "tests", "warnings", "output_tail")}
                            for r, v in a["verification"].items()}
        out["diff"] = a.get("diff")
    return out


# ------------------------------------------------------------------ markdown
def _md_list(items, empty="_none_"):
    items = [i for i in (items or []) if i]
    return "\n".join("- %s" % i for i in items) if items else empty


def to_markdown(c):
    d, obs, ai = c["dependency"], c["observed"], c["ai_generated"]
    v = c["verdict"]["value"]
    L = []
    L.append("# Dependency Exit Capsule: `%s`\n" % d["name"])
    L.append("**Verdict:** %s `%s` - %s  " % (ICON.get(v, ""), v, c["verdict"]["meaning"]))
    L.append("**Risk:** %s (score %d)  " % (obs["risk"]["level"], obs["risk"]["score"]))
    L.append("**Target:** %s @ `%s`, Python %s\n" % (c["target"]["repository"], (c["target"]["commit"] or "?")[:10], c["target"]["python"]))
    L.append("> 🔍 **OBSERVED** = measured by DepExit (manifests, PyPI, AST scan, real installs and test runs).  ")
    L.append("> 🤖 **AI** = generated by %s. AI content is a suggestion, not proof.\n" % (ai["model"] or "AI (disabled)"))

    L.append("## 1. Dependency details 🔍 OBSERVED\n")
    L.append("| Field | Value |\n|---|---|")
    L.append("| Import names | %s |" % ", ".join("`%s`" % m for m in d["modules"]))
    L.append("| Installed version (baseline) | %s |" % (d["installed_version"] or "-"))
    L.append("| Latest on PyPI | %s (released %s) |" % (d["latest_version"] or "-", (obs["pypi"].get("latest_release_date") or "-")[:10]))
    L.append("| Development status | %s |" % (", ".join(obs["pypi"].get("dev_status") or []) or "-"))
    L.append("| Console scripts | %s |" % (", ".join(d["console_scripts"]) or "-"))
    for e in obs["declarations"]:
        L.append("| Declared in `%s:%s` (%s) | `%s` |" % (e["file"], e["line"], e["group"], e["raw"]))
    if not obs["declarations"]:
        L.append("| Declared in | **not declared anywhere** |")
    L.append("")

    L.append("## 2. Risk indicators 🔍 OBSERVED\n")
    if obs["risk"]["indicators"]:
        L.append("| Sev | Indicator | Detail | Evidence |\n|---|---|---|---|")
        for i in obs["risk"]["indicators"]:
            L.append("| %s | `%s` | %s | %s |" % ("●" * i["severity"], i["id"], i["detail"], _cell(i["evidence"])))
    else:
        L.append("_no indicators_")
    L.append("")

    L.append("## 3. Usage locations 🔍 OBSERVED\n")
    rows = [(i["file"], i["line"], "import" + (" (lazy, in `%s`)" % i["scope"] if i["lazy"] else "")
             + (" (side-effect only)" if i["side_effect_only"] else ""), i["statement"]) for i in obs["usage"]["imports"]]
    rows += [(u["file"], u["line"], u["kind"] + (" ⚠ private API" if u["private_api"] else ""), u["code"]) for u in obs["usage"]["usages"]]
    rows += [(t["file"], t["line"], "non-Python reference", t["code"]) for t in obs["usage"]["non_python_references"]]
    if rows:
        L.append("| Location | Kind | Code |\n|---|---|---|")
        for f, ln, kind, code in sorted(rows, key=lambda r: (r[0], r[1])):
            L.append("| `%s:%s` | %s | `%s` |" % (f, ln, kind, _cell(code, 110)))
    else:
        L.append("_not referenced in code_")
    L.append("")

    L.append("## 4. Proposed replacement and migration 🤖 AI\n")
    if not ai["enabled"]:
        L.append("_AI disabled for this run._\n")
    elif ai.get("error") and not ai.get("action"):
        L.append("_AI call failed: %s_\n" % ai["error"])
    else:
        rep = ai.get("proposed_replacement") or {}
        L.append("**Assessment:** %s\n" % (ai.get("assessment") or "-"))
        L.append("**Action:** `%s` → **%s** `%s`  " % (ai.get("action"), rep.get("package") or "-", rep.get("requirement") or ""))
        L.append("**Why:** %s\n" % (rep.get("why") or "-"))
        mc = ai.get("manifest_changes") or {}
        L.append("**Manifest changes:** remove %s; add %s\n" % (
            ", ".join("`%s`" % r for r in mc.get("remove") or []) or "-",
            ", ".join("`%s` (%s)" % (a["spec"], a["group"]) for a in mc.get("add") or []) or "-"))
        L.append("**Migration steps**\n")
        L.append("\n".join("%d. %s" % (n, s) for n, s in enumerate(ai.get("migration_steps") or [], 1)) or "_none_")
        L.append("\n**Code changes**\n")
        for ch in ai.get("code_changes") or []:
            L.append("- `%s`: %s" % (ch["file"], ch.get("why") or ""))
        if not ai.get("code_changes"):
            L.append("_none_")
        L.append("\n**Suggested tests**\n")
        L.append(_md_list(ai.get("suggested_tests")))
        if ai.get("validation_problems_repaired"):
            L.append("\n_The first proposal did not match the source exactly and was repaired by Gemma after DepExit reported:_")
            L.append(_md_list(ai["validation_problems_repaired"]))
        L.append("")

    L.append("## 5. Executed test results 🔍 OBSERVED\n")
    L.append("Baseline (original dependencies):\n")
    L.append("| Install route | Install | Tests |\n|---|---|---|")
    for r, b in obs["baseline"].items():
        L.append("| %s | %s | %s |" % (r, "ok" if b["install_ok"] else "**failed**", _counts(b["tests"])))
    L.append("")
    if not obs["attempts"]:
        L.append("_No migration was executed._\n")
    for a in obs["attempts"]:
        L.append("### Attempt %d - %s `%s`\n" % (a["attempt"], ICON.get(a["verdict"], ""), a["verdict"] or a.get("skipped")))
        if "comparison" not in a:
            L.append("_%s_\n" % (a.get("skipped") or "not executed"))
            continue
        L.append("Applied changes:\n")
        L.append(_md_list(a["apply"]["log"] + ["**ERROR** " + e for e in a["apply"]["errors"]]))
        L.append("\n| Route | Install before → after | Tests before → after | Fixed | Regressed |\n|---|---|---|---|---|")
        for r, cmp in a["comparison"]["routes"].items():
            L.append("| %s | %s → %s | %s → %s | %s | %s |" % (
                r, _ok(cmp["install_ok_before"]), _ok(cmp["install_ok_after"]),
                _counts(cmp["tests_before"]), _counts(cmp["tests_after"]),
                "<br>".join("`%s`" % t for t in cmp["fixed"]) or "-",
                "<br>".join("`%s`" % t for t in cmp["regressed"]) or "-"))
        removed = sorted({w for cmp in a["comparison"]["routes"].values() for w in cmp["warnings_removed"]})
        if removed:
            L.append("\nWarnings that disappeared:\n")
            L.append(_md_list(["`%s`" % _cell(w, 160) for w in removed]))
        imports = a.get("replacement_imports") or {}
        if imports:
            L.append("\nReplacement import check:\n")
            L.append(_md_list(["`import %s` (%s): %s" % (m, r, "ok" if res["ok"] else "FAILED " + res["error"])
                               for m, by in imports.items() for r, res in by.items()]))
        cmds = sorted({run.get("command") for run in a["test_runs"].values() if run.get("command")})
        if cmds:
            L.append("\nCommand: `%s`" % cmds[0].split(" -m ", 1)[-1])
        if a.get("diff"):
            L.append("\n<details><summary>Full diff of this attempt</summary>\n\n```diff\n%s```\n</details>\n" % a["diff"])
        L.append("")

    L.append("## 6. Compatibility gaps\n")
    L.append("**🔍 Observed**\n")
    L.append(_md_list(obs["compatibility_gaps"], "_none observed in the executed checks_"))
    review = ai.get("review") or {}
    L.append("\n**🤖 AI review** (%s confidence%s)\n" % (review.get("confidence", "n/a"),
                                                       ": " + review["confidence_reason"] if review.get("confidence_reason") else ""))
    if review.get("summary"):
        L.append(review["summary"] + "\n")
    L.append(_md_list(review.get("compatibility_gaps")))
    L.append("")

    L.append("## 7. Open concerns and limitations\n")
    L.append("**🔍 Observed**\n")
    L.append(_md_list(obs["open_concerns"]))
    L.append("\n**🤖 AI-identified risks**\n")
    L.append(_md_list((ai.get("risks") or []) + (review.get("unresolved_risks") or [])))
    if review.get("additional_tests"):
        L.append("\n**🤖 Tests the AI recommends adding**\n")
        L.append(_md_list(review["additional_tests"]))
    L.append("\n**Tool limitations**\n")
    L.append(_md_list(c["limitations"]))
    L.append("\n---\n_Machine-readable version: `%s.json`. Apply with `git apply %s.patch`._\n" % (d["name"], d["name"]))
    return "\n".join(L)


def index_markdown(s, capsules, combined):
    run = s["run"]
    L = ["# DepExit report\n",
         "**Target:** %s @ `%s`  " % (run["target"], (run["commit"] or "?")[:10]),
         "**Python:** %s · **Install routes:** %s · **AI:** %s (%d calls)  " % (
             run["python"], ", ".join(run["install_routes"]), run["ai_model"] or "disabled", run["ai_calls"]),
         "**Run:** %s → %s\n" % (run["started"], run["finished"]),
         "## Baseline 🔍 OBSERVED\n",
         "| Route | Install | Tests | Failing |\n|---|---|---|---|"]
    for r, b in s["baseline"].items():
        L.append("| %s | %s | %s | %s |" % (r, _ok(b["install_ok"]), _counts(b["tests"]), "<br>".join("`%s`" % f for f in b["failing"]) or "-"))
    L.append("\n## All dependencies 🔍 OBSERVED\n")
    L.append("| Dependency | Risk | Score | Indicators | Exit capsule | Verdict |\n|---|---|---|---|---|---|")
    for d in s["all_dependencies"]:
        link = "[capsule](dependencies/%s.md)" % d["name"] if d["selected"] else "-"
        L.append("| `%s` | %s | %d | %s | %s | %s %s |" % (d["name"], d["level"], d["score"], ", ".join(d["indicators"]) or "-",
                                                           link, ICON.get(d["verdict"], ""), d["verdict"] or ""))
    if combined:
        L.append("\n## Combined migration 🔍 OBSERVED\n")
        L.append("All individually verified exits applied together: **%s %s**\n" % (ICON.get(combined["verdict"], ""), combined["verdict"]))
        L.append("| Route | Tests before → after | Fixed | Regressed |\n|---|---|---|---|")
        for r, cmp in combined["comparison"]["routes"].items():
            L.append("| %s | %s → %s | %s | %s |" % (r, _counts(cmp["tests_before"]), _counts(cmp["tests_after"]),
                                                  "<br>".join(cmp["fixed"]) or "-", "<br>".join(cmp["regressed"]) or "-"))
        L.append("\nPatch: [`combined-migration.patch`](combined-migration.patch)")
    fc = s.get("forecast")
    if fc:
        versions = list(fc["versions"])
        L.append("\n## Python forecast 🔍 OBSERVED\n")
        L.append("The original project installed and tested on each Python version (%s install).\n" % fc["route"])
        L.append("| | " + " | ".join("Python %s" % fc["versions"][v]["python"] for v in versions) + " |")
        L.append("|---|" + "---|" * len(versions))
        L.append("| install | " + " | ".join(_ok(fc["versions"][v]["install_ok"]) for v in versions) + " |")
        L.append("| tests | " + " | ".join(_counts(fc["versions"][v]["tests"]) for v in versions) + " |")
        L.append("| first error | " + " | ".join(_cell(env_text(fc["versions"][v].get("first_error")), 70) or "-" for v in versions) + " |")
        sym = {"ok": "✅", "deprecated": "⚠️ deprecated", "broken": "❌ broken", "install_failed": "❌ install", "n/a": "–"}
        for dep, row in sorted(fc["matrix"].items()):
            if all(c["state"] in ("ok", "n/a") for c in row.values()):
                continue
            L.append("| `%s` | " % dep + " | ".join(sym[row[v]["state"]] for v in versions) + " |")
    org = s.get("organizer")
    if org:
        L.append("\n## Auto-Organizer\n")
        L.append("Applied on top of the %s. " % org.get("applies_on_top_of", "original repository"))
        L.append("Manifests rebuilt from the observed evidence, then installed and tested: **%s %s**\n"
                 % (ICON.get(org["verdict"], ""), org["verdict"]))
        L.append("| Action | Dependency | Reason (🔍 observed) | Evidence |\n|---|---|---|---|")
        for a in org["actions"]:
            L.append("| %s | `%s` | %s | %s |" % (a["action"], a["dependency"], a["reason"], _cell(a.get("evidence"), 90)))
        if org.get("ai_annotations"):
            L.append("\nRequirement comments marked `(AI)` were written by Gemma 4.")
        L.append("\nPatch: [`organizer.patch`](organizer.patch)")
    L.append("\n---\nFiles: `capsule.json` (index), `dependencies/*.json|md|patch` (one capsule per dependency), "
             "`ai_calls.json` (every Gemma call with prompt hash and raw response).\n")
    return "\n".join(L)


def _cell(text, n=140):
    text = str(text or "").replace("|", "\\|").replace("\n", " ").replace("`", "'")
    return text if len(text) <= n else text[: n - 1] + "…"


def _counts(c):
    if not c:
        return "-"
    order = ("passed", "failed", "error", "skipped", "collection_error")
    return " ".join("%d %s" % (c[k], k) for k in order if c.get(k))


def _ok(v):
    return {True: "ok", False: "**failed**", None: "-"}[v]
